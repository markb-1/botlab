/**
 * Generates packages/core/src/sdk/sdkDts.generated.ts (botlab-sdk.d.ts as a string, spec §5.3) from
 * packages/core/src/sdk/types.ts. Run by `npm run gen:sdk` and `npm run build`; `--check` exits 1 when
 * the committed file is stale (CI / tests).
 */
import fs from 'fs';
import path from 'path';
import { buildSdkDts } from '../packages/core/src/sdk/dts';

const sdkDir = path.join(__dirname, '..', 'packages', 'core', 'src', 'sdk');
const out = path.join(sdkDir, 'sdkDts.generated.ts');

export function renderGenerated(): string {
  const dts = buildSdkDts(fs.readFileSync(path.join(sdkDir, 'types.ts'), 'utf8').replace(/\r\n/g, '\n'));
  return [
    '// GENERATED by scripts/gen-sdk-dts.ts from sdk/types.ts — do not edit; run `npm run gen:sdk`.',
    '/* eslint-disable */',
    '/** botlab-sdk.d.ts (spec §5.3): MCP resource botlab://sdk/types.d.ts and the script typecheck */',
    `export const SDK_DTS: string = ${JSON.stringify(dts)};`,
    '',
  ].join('\n');
}

if (require.main === module) {
  const text = renderGenerated();
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (current !== text) {
      console.error('sdkDts.generated.ts is stale: run `npm run gen:sdk`');
      process.exit(1);
    }
  } else if (current !== text) {
    fs.writeFileSync(out, text);
    console.log(`Wrote ${path.relative(process.cwd(), out)}`);
  }
}
